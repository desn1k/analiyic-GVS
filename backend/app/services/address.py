"""Нормализация адреса — общий ключ для связи приборов/отчётов/ведомости отключений.

У приборного файла и недельного отчёта в названии объекта есть адрес с суффиксом
в скобках (напр. «..., д. 46 (МКД ...)»), а в ведомости отключений — чистый адрес.
UUID-ы (ГУИД/ФИАС/object_id) между системами не совпадают, поэтому связываем по
приведённому адресу.
"""
import re

_PAREN_RE = re.compile(r"\(.*$")
_WS_RE = re.compile(r"\s+")
_REGION_RE = re.compile(r"саратовская\s+обл[а-я.]*\s*,?\s*", re.IGNORECASE)


def normalize_address(s: str | None) -> str:
    if not s:
        return ""
    s = str(s)
    s = _PAREN_RE.sub("", s)          # убрать «(МКД ...)» и всё после скобки
    s = s.lower()
    s = _REGION_RE.sub("", s)         # убрать «саратовская обл,»
    s = s.replace("ё", "е")
    s = s.replace(".", " ")
    s = s.replace(",", " ")
    s = _WS_RE.sub(" ", s).strip()
    return s


def is_matchable_address(norm: str) -> bool:
    """Адрес пригоден для связи, только если содержит номер дома (цифру).

    Иначе объекты-источники типа «Саратов г (ТЭЦ-5)» схлопываются в «саратов г»
    и дают ложные совпадения с любыми отключениями по городу.
    """
    return bool(norm) and any(ch.isdigit() for ch in norm)
